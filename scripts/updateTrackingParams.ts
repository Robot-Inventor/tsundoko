import { writeFile } from "node:fs/promises";

const rulesUrl = "https://raw.githubusercontent.com/DandelionSprout/adfilt/master/LegitimateURLShortener.txt";
const gplMarker = "Below in this paragraph are entries that we borrowed from AdGuard URL Tracking Protection";
const minimumRuleCount = 2000;
const notFound = -1;
const output = new URL("../src/lib/trackingParamRules.ts", import.meta.url);

const response = await fetch(rulesUrl);

if (!response.ok) {
    throw new Error(`Failed to fetch tracking parameter rules: ${String(response.status)}`);
}

const lines = (await response.text()).split(/\r?\n/u);
const gplStart = lines.findIndex((line) => line.includes(gplMarker));

if (gplStart === notFound) {
    throw new Error("Could not find the GPL paragraph marker in the upstream list");
}

const gplEnd = lines.findIndex((line, index) => index > gplStart && line.trim() === "");

if (gplEnd === notFound) {
    throw new Error("Could not find the end of the GPL paragraph in the upstream list");
}

const rules = lines.filter((line, index) => {
    if (index >= gplStart && index <= gplEnd) {
        return false;
    }

    const trimmed = line.trim();

    return trimmed !== "" && !trimmed.startsWith("!") && trimmed.includes("removeparam");
});

if (rules.length < minimumRuleCount) {
    throw new Error(`Expected at least ${String(minimumRuleCount)} rules, got ${String(rules.length)}`);
}

const hasInvalidRegex = (rule: string): boolean => {
    const match = /removeparam=(?<value>\/.*\/[a-z]*)/u.exec(rule);
    const value = match?.groups?.["value"];

    if (!value) {
        return false;
    }

    const pattern = /^\/(?<source>.*)\/(?<flags>[a-z]*)$/u.exec(value);
    const source = pattern?.groups?.["source"];
    const flags = pattern?.groups?.["flags"];

    if (typeof source !== "string" || typeof flags !== "string") {
        return true;
    }

    try {
        new RegExp(source, flags);

        return false;
    } catch {
        return true;
    }
};

const invalidRule = rules.find(hasInvalidRegex);

if (invalidRule) {
    throw new Error(`Invalid regular expression in rule: ${invalidRule}`);
}

const content = [
    "// Generated by scripts/updateTrackingParams.ts. Do not edit by hand.",
    "// Source: https://github.com/DandelionSprout/adfilt/blob/master/LegitimateURLShortener.txt",
    "// Licensed under Dandelicence v1.4: https://github.com/DandelionSprout/Dandelicence",
    "// Rules borrowed from AdGuard URL Tracking Protection (GPL-3.0) are excluded.",
    "",
    "const trackingParamRules = [",
    rules.map((rule) => `    ${JSON.stringify(rule)}`).join(",\n"),
    "] as const;",
    "",
    "export { trackingParamRules };",
    ""
].join("\n");

await writeFile(output, content);
process.stdout.write(`Wrote ${String(rules.length)} rules to ${output.pathname}\n`);
